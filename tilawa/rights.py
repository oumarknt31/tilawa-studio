"""How likely a video taken from a link is to be claimed for copyright once posted.

Nobody can know for sure before uploading: YouTube (Content ID), TikTok and Meta
(Rights Manager) compare each upload's sound with the recordings their rights
holders registered, and none of them lets an app ask in advance. So this is an
estimate from what the link says about itself: its licence, rights notices in
its title and description, whether it comes from an official or large channel,
and on TikTok whether its sound is the poster's own. The page explains what each
platform does with a claim (index.html, rightsCard)."""

from __future__ import annotations

import re

# rights notices (several languages); "copyright free" and the like are looked for first
_FREE = re.compile(r"(no|free of|without|sans|bebas)\s*-?\s*copyright|copyright[ -]?free|libre de droits|sans droits"
                   r"|بدون حقوق|بدون حقوق نشر|free to use|royalty[ -]?free", re.I)
_NOTICE = re.compile(r"©|℗|all rights reserved|tous droits réservés|جميع الحقوق محفوظة|حقوق النشر|copyright"
                     r"|licensed to youtube|exclusive|حصري|official (audio|video|channel)", re.I)
_ORIGINAL_SOUND = re.compile(r"original sound|son original|sonido original|الصوت الأصلي|suara asli|orijinal ses", re.I)

BIG_CHANNEL = 500_000  # followers: channels this large usually have their recordings registered
_YT_LICENCE = re.compile(r"licensed to youtube|content id", re.I)
# a recording sent to the music stores by a distributor (YouTube's "Art Track" descriptions, "- Topic" channels)
_DISTRIBUTED = re.compile(r"provided to youtube by|auto-generated by youtube|℗", re.I)

# Each platform matches uploads only against what rights holders registered with it: YouTube's Content ID,
# TikTok's own system, Meta's Rights Manager (one for Instagram and Facebook). A video can be claimed on one
# and fine on another, so each gets its own estimate.
PLATFORMS = ("youtube", "tiktok", "instagram", "facebook")
_SYSTEM = {"youtube": "youtube", "tiktok": "tiktok", "instagram": "meta", "facebook": "meta"}
_RANK = {"low": 0, "medium": 1, "high": 2}


def assess(info: dict) -> dict:
    """{site, title, channel, level, platforms: {youtube: {level, why}, ...}, reasons: [{key, ...}]} from yt-dlp's info.
    reasons keys: cc, says_free, distributed, notice, official, big, music, original_sound, someone_else.
    level: the highest of the platforms'."""
    site = (info.get("extractor_key") or info.get("extractor") or "").lower()
    site = next((s for s in ("youtube", "tiktok", "instagram", "facebook") if s in site), site or "web")
    channel = info.get("channel") or info.get("uploader") or ""
    text = " ".join(str(info.get(k) or "") for k in ("title", "description"))
    followers = info.get("channel_follower_count") or 0
    reasons = []
    track, artist = info.get("track"), info.get("artist")
    free = _FREE.search(text)
    if info.get("license") and "creative commons" in str(info["license"]).lower():
        reasons.append({"key": "cc", "license": info["license"]})
    elif free:
        reasons.append({"key": "says_free"})  # the uploader's word: not a licence
    if _DISTRIBUTED.search(text) or channel.endswith(" - Topic"):
        reasons.append({"key": "distributed"})
    if track and not _ORIGINAL_SOUND.search(f"{track} {artist or ''}"):
        reasons.append({"key": "music", "track": track, "artist": artist or ""})
    elif track:
        reasons.append({"key": "original_sound"})
    if _NOTICE.search(text) and not free:
        reasons.append({"key": "notice", "youtube": bool(_YT_LICENCE.search(text))})
    if re.search(r"official|رسمي|الرسمية", channel, re.I):
        reasons.append({"key": "official", "channel": channel})
    elif followers >= BIG_CHANNEL or info.get("channel_is_verified"):
        reasons.append({"key": "big", "channel": channel, "followers": followers})
    reasons.append({"key": "someone_else", "channel": channel})
    platforms = by_platform(site, reasons)
    level = max((x["level"] for x in platforms.values()), key=_RANK.get)
    return {"site": site, "title": info.get("title") or "", "channel": channel, "level": level,
            "platforms": platforms, "reasons": reasons}


def by_platform(site: str, reasons: list[dict]) -> dict:
    """{platform: {"level", "why": [keys]}} from what the link says about itself (also for assessments saved
    before there was one per platform). Someone else's recording: possible everywhere ("medium"). A rights
    holder protects it where they publish it (notice, official or large channel: high on the site it comes
    from); a distributed recording or a commercial track is registered almost everywhere."""
    out = {p: {"level": "medium", "why": ["someone_else"]} for p in PLATFORMS}
    keys = {r["key"]: r for r in reasons}
    if "cc" in keys and "distributed" not in keys and "music" not in keys:
        return {p: {"level": "low", "why": ["cc"]} for p in PLATFORMS}

    def high(p: str, why: str) -> None:
        if out[p]["level"] != "high":
            out[p] = {"level": "high", "why": []}
        out[p]["why"].append(why)

    home = [p for p in PLATFORMS if _SYSTEM[p] == _SYSTEM.get(site)]
    for p in PLATFORMS:
        if "distributed" in keys:
            high(p, "distributed")
        if "music" in keys:
            if p == "tiktok":  # in TikTok's own music library: allowed from a personal account
                out[p]["why"].append("tiktok_library")
            else:
                high(p, "music")
        if "notice" in keys and (p in home or (p == "youtube" and keys["notice"].get("youtube"))):
            high(p, "notice")
        for k in ("official", "big"):
            if k in keys and p in home:
                high(p, k)
    return out
